import { expect, test } from '@playwright/test';

import { API_URL } from '../config';

// The datasets of the instance in the admin UI (issue #527). The browser
// suite runs on SQLite, a driver without schemas: the page shows the catalog
// and the instruction of every dataset, and nothing that would install,
// switch or delete one. What an installation does is the subject of the
// server suites on Postgres.
test.describe('datasets', () => {
  for (const [locale, manual, instruction] of [
    ['en', 'Upload files manually', 'How to install'],
    ['ru', 'Загрузить файлы вручную', 'Как установить'],
    ['ar', 'رفع الملفات يدويًا', 'طريقة التثبيت'],
  ]) {
    test(`OpenGloss groups its files and offers manual upload (${locale})`, async ({ page }) => {
      await page.goto(`/${locale}/managing/datasets`);
      await page.getByTestId('dataset-opengloss').getByRole('button', { name: instruction }).click();
      const dialog = page.getByRole('dialog');
      await expect(dialog.locator('input[type="file"]')).toHaveCount(0);
      for (const table of ['senses', 'lexicon']) {
        const group = dialog.getByTestId(`source-group-${table}`);
        await expect(group.getByRole('heading')).toContainText(table);
        await expect(group.getByRole('link')).toHaveCount(6);
      }
      await dialog.getByRole('radio', { name: manual }).check();
      for (const table of ['senses', 'lexicon']) {
        await expect(dialog.getByTestId(`source-group-${table}`).locator('input[type="file"]')).toHaveCount(3);
      }
    });
  }

  test('the managing page links the datasets page', async ({ page }) => {
    await page.goto('/en/managing');

    await page.getByRole('link', { name: 'Datasets' }).click();
    await expect(page).toHaveURL(/\/en\/managing\/datasets$/);
    await expect(page.getByRole('heading', { level: 2, name: 'Datasets' })).toBeVisible();
  });

  test('shows every dataset of the catalog with its license, the one of the project active', async ({
    page,
  }) => {
    await page.goto('/en/managing/datasets');

    await expect(page.getByTestId('datasets-unsupported')).toContainText('needs a Postgres database');
    // an installed dataset is read by the public API before it is activated (issue #528)
    await expect(page.getByTestId('datasets-public-note')).toContainText(
      'An installed dataset is public, active or not: GET /api/v1/words/{word}/datasets',
    );

    const own = page.getByTestId('dataset-default');
    await expect(own).toContainText('Vocab Bloom Hub English dataset');
    await expect(own).toContainText('active');
    await expect(own.getByRole('link', { name: /CC-BY-4\.0/ })).toHaveAttribute(
      'href',
      'https://creativecommons.org/licenses/by/4.0/',
    );
    await expect(own).toContainText('Generated by language models');
    // everything done with a dataset starts on its card (issue #540)
    await expect(own.getByRole('button', { name: 'Import' })).toBeVisible();
    await expect(own.getByRole('button', { name: 'Export' })).toBeVisible();
    await expect(own.getByRole('button', { name: 'Edit its words' })).toBeVisible();

    const wiktionary = page.getByTestId('dataset-wiktionary');
    await expect(wiktionary).toContainText('English Wiktionary');
    await expect(wiktionary).toContainText('not installed');
    await expect(wiktionary).toContainText('share-alike');
    await expect(wiktionary.getByRole('link', { name: /CC-BY-SA-4\.0/ })).toBeVisible();
    await expect(page.getByTestId('dataset-wordnet')).toContainText('Open English WordNet');
    await expect(page.getByTestId('dataset-wordnet_princeton')).toContainText('Princeton WordNet 3.1');

    // the terms of the catalog are the catalog's: nothing to type them in
    await expect(page.getByRole('button', { name: 'Edit the terms' })).toHaveCount(0);
    await expect(page.getByRole('button', { name: 'Activate' })).toHaveCount(0);
    await expect(page.getByRole('button', { name: 'Delete' })).toHaveCount(0);
  });

  test('the instruction says where to download the file and under which terms the data comes', async ({
    page,
  }) => {
    await page.goto('/en/managing/datasets');

    await page.getByTestId('dataset-wiktionary').getByRole('button', { name: 'How to install' }).click();
    const dialog = page.getByRole('dialog');
    await expect(dialog).toContainText('Install: English Wiktionary');
    await expect(dialog).toContainText('kaikki.org-dictionary-English.jsonl.gz');
    await expect(dialog.getByRole('link', { name: 'Direct download' })).toHaveAttribute(
      'href',
      'https://kaikki.org/dictionary/English/kaikki.org-dictionary-English.jsonl.gz',
    );
    await expect(dialog.getByTestId('share-alike')).toContainText('has to stay under the same license');
    await expect(dialog).toContainText('Wiktionary contributors');
    await expect(dialog).toContainText('Datasets are never mixed');
    await expect(dialog).toContainText('under its license, CC-BY-SA-4.0');
    // the version is what the file says of itself (issue #530)
    await expect(dialog.getByTestId('step-version')).toContainText(
      'The version of the dataset is read from the file',
    );

    // SQLite: the instruction can be read, the file cannot be attached
    await expect(dialog.getByTestId('install-unsupported')).toBeVisible();
    await expect(dialog.getByRole('button', { name: 'Start' })).toBeDisabled();
    await dialog.getByRole('button', { name: 'Close' }).last().click();
    await expect(dialog).toBeHidden();

    // a click outside the dialog closes it too
    await page.getByTestId('dataset-wiktionary').getByRole('button', { name: 'How to install' }).click();
    await expect(dialog).toBeVisible();
    await page.mouse.click(5, 5);
    await expect(dialog).toBeHidden();

    // WordNet takes a second, optional file under a license of its own
    await page.getByTestId('dataset-wordnet').getByRole('button', { name: 'How to install' }).click();
    await expect(page.getByRole('dialog')).toContainText('english-wordnet-2025.zip');
    await expect(page.getByRole('dialog')).toContainText('cmudict.dict');
    await expect(page.getByRole('dialog').getByRole('link', { name: 'BSD 2-Clause License' })).toBeVisible();
  });

  // issue #530: SQLite holds the dataset of the project only, and no source is asked about it
  test('asks no source about the dataset of the project, and shows no notice', async ({ page }) => {
    const updates = page.waitForResponse((response) => response.url().endsWith('/api/en/datasets/updates'));
    await page.goto('/en/managing/datasets');
    expect((await (await updates).json()).datasets).toEqual([]);

    await expect(page.getByTestId('dataset-default')).toContainText('Version');
    await expect(page.locator('[data-testid^="dataset-update-"]')).toHaveCount(0);
    await expect(page.locator('[data-testid^="dataset-source-version-"]')).toHaveCount(0);
  });

  test('the API reports the terms of the project dataset', async ({ request }) => {
    const meta = (await (await request.get(`${API_URL}/v1/meta`)).json()) as {
      data: { notice: string; dataset: string; source: string; license: string };
    };
    expect(meta.data).toEqual(
      expect.objectContaining({ dataset: 'default', source: 'vocab-bloom-hub', license: 'CC-BY-4.0' }),
    );
    expect(meta.data.notice).toContain('Generated by language models');
  });

  test('the old addresses of the import and the export lead to the datasets page', async ({ page }) => {
    for (const path of ['/en/managing/import-dictionary', '/en/managing/export-dictionary']) {
      await page.goto(path);
      await expect(page).toHaveURL(/\/en\/managing\/datasets$/);
    }
    // the managing page offers them no more
    await page.goto('/en/managing');
    await expect(page.getByRole('link', { name: 'Import Dictionary' })).toHaveCount(0);
  });

  test('edits the words of a dataset from its card', async ({ page }) => {
    await page.goto('/en/managing/datasets');
    await page.getByTestId('dataset-default').getByRole('button', { name: 'Edit its words' }).click();
    await expect(page).toHaveURL(/\/en\/managing$/);
    await expect(page.getByTestId('dataset-switch')).toContainText('Vocab Bloom Hub English dataset');
  });

  // issue #540: the datasets of the instance's own need schemas; SQLite holds the one dataset
  test('offers a dataset of the instance’s own under the catalog, and creates none on SQLite', async ({
    page,
  }) => {
    await page.goto('/en/managing/datasets');

    const own = page.getByTestId('own-datasets');
    await expect(own.getByRole('heading', { name: 'Datasets of this instance' })).toBeVisible();
    await expect(own).toContainText('No dataset of your own yet');
    await expect(own.getByRole('button', { name: 'Create a dataset' })).toBeDisabled();

    const refused = await page.request.post(`${API_URL}/en/datasets`, {
      data: { name: 'my_words', title: 'My words', license: { spdx: 'CC0-1.0' }, attribution: 'Me' },
    });
    expect(refused.status()).toBe(409);
    expect((await refused.json()).message).toBe('datasets_not_supported');
  });

  test('the header names the dataset that is edited, and the block under it says what it is', async ({
    page,
  }) => {
    await page.goto('/en/managing');

    const choice = page.getByTestId('dataset-switch');
    await expect(choice).toContainText('Editing:');
    await expect(choice).toContainText('Vocab Bloom Hub English dataset');
    // SQLite: the switch lists the one dataset
    await choice.click();
    await expect(page.locator('.ant-select-item-option')).toHaveCount(1);
    await page.keyboard.press('Escape');

    const block = page.getByTestId('edited-dataset');
    await expect(block).toContainText('You are editing');
    await expect(block).toContainText('Vocab Bloom Hub English dataset');
    await expect(block).toContainText('of the catalog');
    await expect(block.getByRole('link', { name: 'CC-BY-4.0' })).toBeVisible();
    await expect(page.getByTestId('edited-dataset-entries')).not.toHaveText('…');
    // the dataset of the project is no public source: nothing is marked as modified by an edit
    await expect(page.getByTestId('edited-dataset-modified-note')).toHaveCount(0);

    // a dataset the instance does not hold is refused by the routes of the dictionary
    const refused = await page.request.get(`${API_URL}/en/words?dataset=my_words`);
    expect(refused.status()).toBe(404);
  });
});
